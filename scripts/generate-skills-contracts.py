"""Run with nas-adk's environment; Python models are the only format definition."""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from nas.adk.skills import SkillPackage, SkillRef


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts(item) for item in schema["anyOf"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type")
    if kind == "object":
        props = schema.get("properties", {})
        if not props:
            return f"Record<string, {ts(schema.get('additionalProperties', {}))}>"
        required = schema.get("required", [])
        return "{\n" + "\n".join(
            f"  {key}{'' if key in required else '?'}: {ts(value)};"
            for key, value in props.items()) + "\n}"
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}.get(kind, "unknown")


root = Path(__file__).resolve().parents[1] / "lib/skills"
root.mkdir(exist_ok=True)
definitions = {}
for model in (SkillPackage, SkillRef):
    schema = model.model_json_schema()
    definitions.update(schema.pop("$defs", {}))
    definitions[model.__name__] = schema
output = "// Generated by scripts/generate-skills-contracts.py. Do not edit.\n\n"
output += "\n\n".join(f"export type {name} = {ts(schema)};"
                        for name, schema in definitions.items()) + "\n"
artifacts = {"contracts.generated.ts": output, "schema.generated.json": json.dumps(
    {"$defs": definitions, "$ref": "#/$defs/SkillPackage"}, indent=2) + "\n"}
for name, content in artifacts.items():
    target = root / name
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != content:
            raise SystemExit(f"Stale generated contract: {target}")
    else:
        target.write_text(content)
